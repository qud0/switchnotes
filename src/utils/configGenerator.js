// 2. SNR (NAG / Enterprise CLI)
// -------------------------------------------------------------
function generateSNRConfig(switchData, ports, vlans, options = {}) {
  const {
    mgmtVlanId = 10,
    mgmtIp = switchData.ip || '192.168.10.10',
    mgmtMask = '255.255.255.0',
    mgmtGateway = '192.168.10.1',
    enableStp = true,
    enableSnmp = true,
    snmpCommunity = 'public',
    includeComments = true
  } = options;

  const lines = [
    `! ==============================================================================`,
    `! SNR (NAG) Switch Enterprise Configuration`,
    `! Device: ${switchData.name} (${switchData.model || 'SNR-S2985G / S2995G'})`,
    `! Generated by SwitchBook CLI Auto-Provisioning Engine`,
    `! Date: ${new Date().toLocaleString('ru-RU')}`,
    `! ==============================================================================`,
    `system-view`,
    `hostname ${switchData.name}`,
    `!`
  ];

  if (enableStp) {
    lines.push(`! Настройка Spanning Tree (RSTP)`);
    lines.push(`spanning-tree mode rstp`);
    lines.push(`spanning-tree`);
    lines.push(`!`);
  }

  if (enableSnmp) {
    lines.push(`! Настройка SNMP`);
    lines.push(`snmp-server enable`);
    lines.push(`snmp-server community ${snmpCommunity} ro`);
    lines.push(`snmp-server location "${switchData.location || 'Server Rack'}"`);
    lines.push(`!`);
  }

  // Collect all VLANs used by ports
  const usedVlanIds = new Set([mgmtVlanId]);
  ports.forEach(p => {
    if (p.pvid) usedVlanIds.add(p.pvid);
    (p.taggedVlans || []).forEach(v => usedVlanIds.add(v));
  });

  lines.push(`! Создание VLAN и назначение имен`);
  Array.from(usedVlanIds).sort((a, b) => a - b).forEach(vId => {
    const v = vlans.find(vl => vl.id === vId);
    lines.push(`vlan ${vId}`);
    if (includeComments && v?.name) lines.push(` name ${v.name}`);
  });
  lines.push(`!`);

  // Configure Port-Channels (LAGs)
  const lagGroups = {};
  ports.forEach(p => {
    if (p.lagId) {
      if (!lagGroups[p.lagId]) lagGroups[p.lagId] = [];
      lagGroups[p.lagId].push(p);
    }
  });

  if (Object.keys(lagGroups).length > 0) {
    lines.push(`! Настройка интерфейсов агрегации Port-Channel (LACP)`);
    Object.entries(lagGroups).forEach(([lagId, lagPorts]) => {
      const primaryPort = lagPorts[0];
      lines.push(`interface Port-Channel ${lagId}`);
      if (includeComments && primaryPort.lagName) lines.push(` description ${primaryPort.lagName}`);

      if (primaryPort.mode === 'trunk') {
        lines.push(` switchport mode trunk`);
        if (primaryPort.pvid && primaryPort.pvid !== 1) {
          lines.push(` switchport trunk native vlan ${primaryPort.pvid}`);
        }
        if (primaryPort.taggedVlans?.length > 0) {
          lines.push(` switchport trunk allowed vlan ${primaryPort.taggedVlans.join(',')}`);
        }
      } else {
        lines.push(` switchport mode access`);
        lines.push(` switchport access vlan ${primaryPort.pvid || 1}`);
      }
      lines.push(`!`);
    });
  }

  // Physical Ports
  lines.push(`! Настройка физических интерфейсов`);
  ports.forEach(p => {
    lines.push(`interface ${p.name}`);
    if (includeComments && p.description) lines.push(` description ${p.description}`);

    if (!p.enabled || p.mode === 'disabled') {
      lines.push(` shutdown`);
      lines.push(`!`);
      return;
    }

    if (p.lagId) {
      lines.push(` channel-group ${p.lagId} mode active`);
      lines.push(`!`);
      return;
    }

    if (p.mode === 'access') {
      lines.push(` switchport mode access`);
      lines.push(` switchport access vlan ${p.pvid || 1}`);
      lines.push(` spanning-tree edge-port`);
    } else if (p.mode === 'trunk') {
      lines.push(` switchport mode trunk`);
      if (p.pvid && p.pvid !== 1) {
        lines.push(` switchport trunk native vlan ${p.pvid}`);
      }
      if (p.taggedVlans && p.taggedVlans.length > 0) {
        lines.push(` switchport trunk allowed vlan ${p.taggedVlans.join(',')}`);
      }
    }
    lines.push(`!`);
  });

  // Management IP
  lines.push(`! Управление коммутатором (VLAN ${mgmtVlanId})`);
  lines.push(`interface vlan ${mgmtVlanId}`);
  lines.push(` ip address ${mgmtIp.split('/')[0]} ${mgmtMask}`);
  lines.push(` no shutdown`);
  lines.push(`!`);
  if (mgmtGateway) {
    lines.push(`ip default-gateway ${mgmtGateway}`);
    lines.push(`!`);
  }
  lines.push(`save`);

  return lines.join('\n');
}

