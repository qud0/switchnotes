/**
 * CLI Configuration Generator & Auto-Provisioning Engine
 * Supports MikroTik (RouterOS v7 bridge-vlan & RouterOS v6 switch chip),
 * SNR (NAG / Cisco-like Comware/CLI), Cisco IOS / Catalyst,
 * and Ubiquiti EdgeSwitch / UniFi CLI.
 */

export function generateSwitchConfig(switchData, vlans = [], targetVendor = null, options = {}) {
  const vendor = (targetVendor || switchData.vendor || 'MikroTik').toLowerCase();
  const ports = switchData.ports || [];

  if (vendor.includes('mikrotik')) {
    return generateMikroTikConfig(switchData, ports, vlans, options);
  } else if (vendor.includes('cisco')) {
    return generateCiscoConfig(switchData, ports, vlans, options);
  } else if (vendor.includes('snr')) {
    return generateSNRConfig(switchData, ports, vlans, options);
  } else if (vendor.includes('ubiquiti') || vendor.includes('unifi')) {
    return generateUbiquitiConfig(switchData, ports, vlans, options);
  }

  // Fallback to SNR/Cisco style
  return generateSNRConfig(switchData, ports, vlans, options);
}

// -------------------------------------------------------------
// 1. MIKROTIK ROUTEROS (v7 Bridge VLAN Filtering & Management)
// -------------------------------------------------------------
function generateMikroTikConfig(switchData, ports, vlans, options = {}) {
  const {
    mgmtVlanId = 10,
    mgmtIp = switchData.ip || '192.168.10.10/24',
    mgmtGateway = '192.168.10.1',
    dns = '192.168.10.1, 77.88.8.8',
    enableNtp = true,
    enableStp = true,
    enableSnmp = true,
    snmpCommunity = 'public',
    includeComments = true,
    adminUser = 'admin'
  } = options;

  const lines = [
    `# ==============================================================================`,
    `# MikroTik RouterOS v7 - Hardware-Offloaded Bridge VLAN Filtering`,
    `# Device: ${switchData.name} (${switchData.model || 'CRS/CSS Series'})`,
    `# Generated by SwitchBook CLI Auto-Provisioning Engine`,
    `# Date: ${new Date().toLocaleString('ru-RU')}`,
    `# ==============================================================================`,
    ``,
    `# [Шаг 1] Идентификация и системные настройки`,
    `/system identity set name="${switchData.name}"`,
    `/system clock set time-zone-name=Europe/Moscow`,
    enableNtp ? `/system ntp client set enabled=yes servers=192.168.10.1,pool.ntp.org` : '',
    enableSnmp ? `/snmp set enabled=yes contact="Network Admin" location="${switchData.location || 'Server Room'}"` : '',
    enableSnmp ? `/snmp community set [find default=yes] name=${snmpCommunity} addresses=192.168.10.0/24` : '',
    ``,
    `# [Шаг 2] Агрегация каналов (LACP 802.3ad / Bonding)`
  ].filter(l => l !== '');

  // Group ports by lagId
  const lagGroups = {};
  ports.forEach(p => {
    if (p.lagId) {
      if (!lagGroups[p.lagId]) lagGroups[p.lagId] = [];
      lagGroups[p.lagId].push(p);
    }
  });

  const createdBondNames = new Set();
  if (Object.keys(lagGroups).length > 0) {
    Object.entries(lagGroups).forEach(([lagId, lagPorts]) => {
      const bondName = `bond${lagId}`;
      const slaves = lagPorts.map(p => p.name).join(',');
      const comment = lagPorts[0]?.lagName || `LAG-${lagId}`;
      lines.push(`/interface bonding add name=${bondName} slaves=${slaves} mode=802.3ad transmit-hash-policy=layer-2-and-3 comment="${comment}"`);
      createdBondNames.add(bondName);
    });
  } else {
    lines.push(`# (Агрегированные интерфейсы не назначены)`);
  }

  lines.push(``);
  lines.push(`# [Шаг 3] Создание системного Bridge с поддержкой RSTP`);
  const stpProtocol = enableStp ? 'rstp' : 'none';
  lines.push(`/interface bridge add name=bridge protocol-mode=${stpProtocol} vlan-filtering=no comment="Core L2 Bridge"`);
  lines.push(``);
  lines.push(`# [Шаг 4] Добавление физических портов и LAG в мост (Bridge Ports)`);

  const bridgeInterfaces = [];

  // Add bonds to bridge
  Object.entries(lagGroups).forEach(([lagId, lagPorts]) => {
    const bondName = `bond${lagId}`;
    const primaryPort = lagPorts[0];
    const pvid = primaryPort.pvid || 1;
    lines.push(`/interface bridge port add bridge=bridge interface=${bondName} pvid=${pvid} comment="${primaryPort.lagName || bondName}"`);
    bridgeInterfaces.push({ name: bondName, port: primaryPort });
  });

  // Add physical non-LAG ports
  ports.forEach(p => {
    if (!p.enabled || p.mode === 'disabled') {
      lines.push(`/interface set [find default-name=${p.name}] disabled=yes comment="Disabled / Заблокирован"`);
      return;
    }

    if (p.lagId) return; // already added via bonding interface

    const commentStr = includeComments && p.description ? ` comment="${p.description}"` : '';
    const pvid = p.pvid || 1;
    lines.push(`/interface bridge port add bridge=bridge interface=${p.name} pvid=${pvid} hw=yes${commentStr}`);
    bridgeInterfaces.push({ name: p.name, port: p });
  });

  lines.push(``);
  lines.push(`# [Шаг 5] Таблица членства в VLAN (Bridge VLANs Table)`);

  const vlanMap = {};
  vlans.forEach(v => {
    vlanMap[v.id] = { id: v.id, name: v.name, tagged: [], untagged: [] };
  });

  // Add bridge CPU itself to management VLAN tagged list
  if (vlanMap[mgmtVlanId]) {
    vlanMap[mgmtVlanId].tagged.push('bridge');
  }

  bridgeInterfaces.forEach(({ name, port }) => {
    if (port.mode === 'access') {
      if (vlanMap[port.pvid]) {
        vlanMap[port.pvid].untagged.push(name);
      }
    } else if (port.mode === 'trunk') {
      if (port.pvid && vlanMap[port.pvid]) {
        vlanMap[port.pvid].untagged.push(name);
      }
      (port.taggedVlans || []).forEach(vId => {
        if (vlanMap[vId] && !vlanMap[vId].tagged.includes(name)) {
          vlanMap[vId].tagged.push(name);
        }
      });
    }
  });

  Object.values(vlanMap).forEach(v => {
    if (v.tagged.length === 0 && v.untagged.length === 0) return;

    const parts = [`/interface bridge vlan add bridge=bridge vlan-ids=${v.id}`];
    if (v.tagged.length > 0) parts.push(`tagged="${v.tagged.join(',')}"`);
    if (v.untagged.length > 0) parts.push(`untagged="${v.untagged.join(',')}"`);
    if (includeComments && v.name) parts.push(`comment="${v.name}"`);
    lines.push(parts.join(' '));
  });

  lines.push(``);
  lines.push(`# [Шаг 6] Интерфейс управления коммутатором (In-Band Management)`);
  lines.push(`/interface vlan add name=vlan-mgmt vlan-id=${mgmtVlanId} interface=bridge comment="Management Interface"`);
  lines.push(`/ip address add address=${mgmtIp} interface=vlan-mgmt comment="Management IP"`);
  if (mgmtGateway) {
    lines.push(`/ip route add gateway=${mgmtGateway} comment="Default Gateway"`);
  }
  if (dns) {
    lines.push(`/ip dns set servers=${dns}`);
  }

  lines.push(``);
  lines.push(`# [Шаг 7] БЕЗОПАСНОСТЬ: Включение Bridge VLAN Filtering`);
  lines.push(`# ВНИМАНИЕ: Выполнять последней строкой!`);
  lines.push(`/interface bridge set bridge vlan-filtering=yes`);

  return lines.join('\n');
}

