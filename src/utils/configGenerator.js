// 4. UBIQUITI EDGESWITCH / UNIFI CLI
// -------------------------------------------------------------
function generateUbiquitiConfig(switchData, ports, vlans, options = {}) {
  const {
    mgmtVlanId = 10,
    mgmtIp = switchData.ip || '192.168.10.10',
    mgmtMask = '255.255.255.0',
    mgmtGateway = '192.168.10.1',
    includeComments = true
  } = options;

  const lines = [
    `! ==============================================================================`,
    `! Ubiquiti EdgeSwitch / UniFi CLI Configuration`,
    `! Device: ${switchData.name} (${switchData.model || 'UniFi / EdgeSwitch'})`,
    `! Generated by SwitchBook CLI Auto-Provisioning Engine`,
    `! Date: ${new Date().toLocaleString('ru-RU')}`,
    `! ==============================================================================`,
    `enable`,
    `configure`,
    `hostname ${switchData.name}`,
    `!`
  ];

  const usedVlanIds = new Set([mgmtVlanId]);
  ports.forEach(p => {
    if (p.pvid) usedVlanIds.add(p.pvid);
    (p.taggedVlans || []).forEach(v => usedVlanIds.add(v));
  });

  Array.from(usedVlanIds).sort((a, b) => a - b).forEach(vId => {
    const v = vlans.find(vl => vl.id === vId);
    lines.push(`vlan database`);
    lines.push(` vlan ${vId}`);
    if (includeComments && v?.name) lines.push(` vlan name ${vId} "${v.name}"`);
    lines.push(`exit`);
  });

  lines.push(`!`);

  // Interfaces
  ports.forEach((p, idx) => {
    const ifaceName = p.name.includes('/') ? p.name : `0/${idx + 1}`;
    lines.push(`interface ${ifaceName}`);

    if (includeComments && p.description) {
      lines.push(` description "${p.description}"`);
    }

    if (!p.enabled || p.mode === 'disabled') {
      lines.push(` shutdown`);
      lines.push(`exit`);
      return;
    }

    if (p.lagId) {
      lines.push(` channel-group ${p.lagId} mode active`);
      lines.push(`exit`);
      return;
    }

    if (p.mode === 'access') {
      lines.push(` vlan pvid ${p.pvid || 1}`);
      lines.push(` vlan participation untagged ${p.pvid || 1}`);
    } else if (p.mode === 'trunk') {
      if (p.pvid) {
        lines.push(` vlan pvid ${p.pvid}`);
        lines.push(` vlan participation untagged ${p.pvid}`);
      }
      (p.taggedVlans || []).forEach(vId => {
        lines.push(` vlan participation tagged ${vId}`);
      });
    }

    lines.push(`exit`);
  });

  // Management IP
  lines.push(`!`);
  lines.push(`network mgmt_vlan ${mgmtVlanId}`);
  lines.push(`network parms ${mgmtIp.split('/')[0]} ${mgmtMask} ${mgmtGateway || ''}`);
  lines.push(`exit`);
  lines.push(`write memory`);

  return lines.join('\n');
}
